// Store schema v2: rooms and the durable per-room message log.
//
// A NEW module beside the untouched v0.1 store (../database.mjs). The v0.1
// daemon keeps using the global-AUTOINCREMENT schema; this store owns the
// schema-v2 conversation substrate for Stories 1.3-1.8: rooms (broadcast and
// direct with a canonical pair key), a room-local contiguous append-only
// message log keyed (room_id, seq), idempotent sends by the tuple
// (actor fingerprint, room, client_message_id), and protocol-level DM privacy
// enforced at the store boundary.
//
// The message log is append-only: no mutation verb of any kind ever touches a
// committed message row. Reply targets resolve room-locally against
// (room_id, seq). A v1 database file is refused, never migrated (Epic 2 owns
// migration). Every error code is a member of PUBLIC_ERRORS or
// INTERNAL_ERROR_CODES, both declared in ../constants.mjs: public codes for
// caller-facing outcomes, internal codes for invariants that are not
// wire-visible.

