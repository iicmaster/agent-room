function createSchema(database) {
  withImmediateTransaction(database, () => {
    // Re-read inside the write transaction: a concurrent opener may have
    // created the schema between our outer probe and this transaction. The
    // loser of that race no-ops instead of crashing on existing tables.
    const current = Number(pragmaValue(database, 'PRAGMA user_version'))
    if (current === ROOM_LOG_SCHEMA_VERSION) return
    if (current !== 0) {
      fail(
        'database_schema_unsupported',
        `database schema ${current} is not supported; expected ${ROOM_LOG_SCHEMA_VERSION} (the one-time v1→v2 migration runs at server startup, never on this raw store path)`,
      )
    }

    database.exec(`
      ${roomsTableDdl('rooms')}

      ${directMembersTableDdl()}

      ${messagesTableDdl('messages')}

      PRAGMA user_version = ${ROOM_LOG_SCHEMA_VERSION};
    `)
  })
}

// Schema probe: fresh files (user_version 0) proceed to schema creation;
// version 2 files proceed to verification; anything else — a v1 file above
// all — is refused untouched, because migration belongs to Epic 2. A version
// 0 file that already carries application tables is likewise refused rather
// than crashed into. The probe runs BEFORE any pragma or permission change so
// a refused file's bytes are never modified by this store.
function probeSchemaVersion(database) {
  // The version and table-structure reads must share one snapshot: a
  // concurrent opener commits (tables + user_version = 2) atomically, and a
  // two-read probe without a transaction could straddle that commit and
  // mistake a legitimate v2 file for a v0 file carrying foreign tables. A
  // deferred read transaction gives both reads one consistent snapshot.
  database.exec('BEGIN DEFERRED')
  try {
    let version
    try {
      version = Number(pragmaValue(database, 'PRAGMA user_version'))
    } catch (error) {
      if (error?.errcode === SQLITE_NOTADB || error?.errcode === SQLITE_CORRUPT) {
        fail('database_schema_unsupported', 'existing database file is not a usable SQLite database')
      }
      throw error
    }
    if (version === ROOM_LOG_SCHEMA_VERSION) return version
    if (version !== 0) {
      fail(
        'database_schema_unsupported',
        `database schema ${version} is not supported; expected ${ROOM_LOG_SCHEMA_VERSION} (the one-time v1→v2 migration runs at server startup, never on this raw store path)`,
      )
    }
    let applicationTables
    try {
      applicationTables = Number(database.prepare(`
        SELECT COUNT(*) AS count
        FROM sqlite_master
        WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
      `).get().count)
    } catch (error) {
      if (error?.errcode === SQLITE_BUSY) {
        fail('database_busy', 'agent-room database stayed busy while probing the schema version')
      }
      throw error
    }
    if (applicationTables > 0) {
      fail(
        'database_schema_unsupported',
        'database file already contains tables at schema version 0 and cannot be adopted',
      )
    }
    return 0
  } finally {
    try {
      database.exec('COMMIT')
    } catch {
      try {
        database.exec('ROLLBACK')
      } catch {
        // The connection is failing; the caller closes it.
      }
    }
  }
}

function isUnusableDatabaseError(error) {
  return error?.errcode === SQLITE_NOTADB || error?.errcode === SQLITE_CORRUPT
}

// Synchronous backoff for the open path: concurrent openers must not fail
// fast, and the open sequence is synchronous, so the retry sleeps via
// Atomics.wait (a short blocking wait is acceptable during startup).
function sleepSync(milliseconds) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, milliseconds)
}

function isBusyError(error) {
  return error?.errcode === SQLITE_BUSY
    || (error instanceof AgentRoomRuntimeError && error.code === 'database_busy')
}

function withBusyRetry(operation) {
  let attempt = 0
  for (;;) {
    try {
      return operation()
    } catch (error) {
      attempt += 1
      if (!isBusyError(error) || attempt > STORE_OPEN_BUSY_RETRY_LIMIT) throw error
      sleepSync(STORE_OPEN_BUSY_BACKOFF_MS * attempt)
    }
  }
}

function verifyStrictTables(database) {
  const strictTables = database.prepare(`
    SELECT name, strict
    FROM pragma_table_list
    WHERE schema = 'main'
      AND name IN ('rooms', 'direct_members', 'messages', 'realms', 'chat_id_claims', 'enrolled_actors', 'invites', 'invite_consumptions', 'banned_actors')
  `).all()
  const strictByName = new Map(strictTables.map(row => [row.name, Number(row.strict)]))
  for (const name of ['rooms', 'direct_members', 'messages', 'realms', 'chat_id_claims', 'enrolled_actors', 'invites', 'invite_consumptions', 'banned_actors']) {
    if (strictByName.get(name) !== 1) {
      fail('database_schema_invalid', `database table ${name} is missing or is not STRICT`)
    }
  }
}

// Story 1.3 (additive, no schema-version bump): the realms table joins the
