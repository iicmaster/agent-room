// Claim timestamps are canonical ISO 8601 strings — the same form every other
// timestamp in this store uses — normalized at write time so the prune
// comparison is exact. An injected value must parse as a date; anything else
// is a coded internal failure.
function requireClaimTimestamp(value) {
  if (value === undefined || value === null) return new Date().toISOString()
  if (typeof value !== 'string') {
    fail('invalid_argument', 'lastSeenAt must be an ISO 8601 timestamp string')
  }
  const parsed = Date.parse(value)
  if (!Number.isFinite(parsed)) {
    fail('invalid_argument', 'lastSeenAt must be an ISO 8601 timestamp string')
  }
  return new Date(parsed).toISOString()
}

// Canonical DM pair identity: the two fingerprints sorted lexicographically,
// so (a, b) and (b, a) derive the same key and openDirectRoom is idempotent
// in either argument order. Fingerprints are fixed length, so the sort is
// stable. The lexicographic minimum doubles as the deterministic
// created_by_fingerprint for a direct room.
function canonicalDirectPair(firstFingerprint, secondFingerprint) {
  const [min, max] = [firstFingerprint, secondFingerprint].sort()
  return Object.freeze({ min, max, pairKey: `${DIRECT_PAIR_KEY_PREFIX}${min}:${max}` })
}

function pragmaValue(database, sql) {
  const row = database.prepare(sql).get()
  return row ? Object.values(row)[0] : undefined
}

// Pragma discipline mirrors the v0.1 store's configureConnection exactly:
// WAL, synchronous=FULL, foreign keys ON, busy_timeout 5000,
// wal_autocheckpoint 1000 — asserted after applying, never assumed. The busy
// timeout is applied FIRST: it is the only guard for the journal-mode switch,
// which is the open path's first contended write under concurrent openers.
function configureConnection(database) {
  const sqliteVersion = String(
    database.prepare('SELECT sqlite_version() AS version').get().version,
  )
  assertSupportedRuntime({ sqliteVersion })

  database.exec('PRAGMA busy_timeout = 5000;')

  let journalMode
  try {
    journalMode = String(pragmaValue(database, 'PRAGMA journal_mode = WAL')).toLowerCase()
  } catch (error) {
    if (error?.errcode === SQLITE_BUSY) {
      fail('database_busy', 'agent-room database stayed busy while enabling WAL journal mode')
    }
    throw error
  }
  if (journalMode !== 'wal') {
    fail('wal_unavailable', 'agent-room requires SQLite WAL journal mode')
  }

  database.exec(`
    PRAGMA synchronous = FULL;
    PRAGMA foreign_keys = ON;
    PRAGMA busy_timeout = 5000;
    PRAGMA wal_autocheckpoint = 1000;
  `)

  const pragmas = Object.freeze({
    synchronous: Number(pragmaValue(database, 'PRAGMA synchronous')),
    foreignKeys: Number(pragmaValue(database, 'PRAGMA foreign_keys')) === 1,
    busyTimeout: Number(pragmaValue(database, 'PRAGMA busy_timeout')),
    walAutoCheckpoint: Number(pragmaValue(database, 'PRAGMA wal_autocheckpoint')),
  })
  if (
    pragmas.synchronous !== 2
    || pragmas.foreignKeys !== true
    || pragmas.busyTimeout !== 5000
    || pragmas.walAutoCheckpoint !== 1000
  ) {
    fail('database_configuration_failed', 'SQLite connection pragmas were not applied')
  }
  return { sqliteVersion, journalMode, pragmas }
}

function withImmediateTransaction(database, operation) {
  try {
    database.exec('BEGIN IMMEDIATE')
  } catch (error) {
    // Under contention the connection waits busy_timeout, then surfaces
    // SQLITE_BUSY: the write never started, so it maps to a coded internal
    // error instead of a raw SqliteError.
    if (error?.errcode === SQLITE_BUSY) {
      fail('database_busy', 'agent-room database write lock stayed busy; the operation never started')
    }
    throw error
  }
  try {
    const result = operation()
    database.exec('COMMIT')
    return result
  } catch (error) {
    try {
      database.exec('ROLLBACK')
    } catch {
      // Preserve the operation error; the connection will surface later failures.
    }
    throw error
  }
}

// A CHECK clause enforcing the exact fingerprint shape at the schema level:
// fixed total length, the sha256: prefix, and a 64-character tail drawn only
// from [0-9a-f] (the NOT GLOB guarantees no character outside the class).
// SQLite CHECKs pass on NULL results, so this also admits the NULL creator of
// the implicit Broadcast Room.
function fingerprintCheck(column) {
  const tailStart = FINGERPRINT_PREFIX.length + 1
  return `CHECK (length(${column}) = ${FINGERPRINT_PREFIX.length + FINGERPRINT_HEX_LENGTH}
          AND substr(${column}, 1, ${FINGERPRINT_PREFIX.length}) = '${FINGERPRINT_PREFIX}'
          AND substr(${column}, ${tailStart}) NOT GLOB '*[^0-9a-f]*')`
}

// The rooms table DDL, parameterized by table name so the nullable-creator
// convergence rebuild (ensureNullableRoomCreator), the fresh-schema path, and
// the v1→v2 migration (migrate-v1.mjs) share one definition. created_by_
// fingerprint is NULLABLE: the implicit Broadcast Room exists before any Actor
// enrolls and must never carry a fabricated creator identity.
export function roomsTableDdl(tableName) {
  return `
    CREATE TABLE ${tableName} (
      id TEXT PRIMARY KEY,
      kind TEXT NOT NULL,
      title TEXT,
      pair_key TEXT UNIQUE,
      created_by_fingerprint TEXT,
      created_at TEXT NOT NULL,
      CHECK (kind IN ('broadcast', 'direct')),
      CHECK ((kind = 'direct') = (pair_key IS NOT NULL)),
      CHECK (kind = 'direct' OR title IS NOT NULL),
      CHECK (kind = 'direct' OR length(title) BETWEEN 1 AND ${TITLE_MAX}),
      CHECK (length(id) BETWEEN 1 AND ${IDENTIFIER_MAX}),
      ${fingerprintCheck('created_by_fingerprint')}
    ) STRICT;
  `
}

// The durable log DDL, parameterized by table name for the same three
// consumers (fresh schema, nullable-creator rebuild, v1 migration). The
// composite primary key is what makes reply targets room-local, and the
// self-referential FK is why the migration must copy replies after (or in the
// ordered company of) their targets.
export function messagesTableDdl(tableName) {
  return `
    -- The durable log: keyed (room_id, seq), room-local contiguous
    -- sequences from 1, and no mutation path of any kind.
    CREATE TABLE ${tableName} (
      room_id TEXT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
      seq INTEGER NOT NULL,
      actor_fingerprint TEXT NOT NULL,
      chat_id TEXT NOT NULL,
      client_message_id TEXT NOT NULL,
      text TEXT NOT NULL,
      reply_to_seq INTEGER,
      created_at TEXT NOT NULL,
      PRIMARY KEY (room_id, seq),
      UNIQUE (room_id, actor_fingerprint, client_message_id),
      FOREIGN KEY (room_id, reply_to_seq)
        REFERENCES messages(room_id, seq) ON DELETE RESTRICT,
      CHECK (seq >= 1),
      CHECK (reply_to_seq IS NULL OR reply_to_seq >= 1),
      ${fingerprintCheck('actor_fingerprint')},
      CHECK (length(chat_id) BETWEEN 1 AND ${CHAT_ID_MAX}),
      CHECK (length(client_message_id) BETWEEN 1 AND ${CLIENT_MESSAGE_ID_MAX}),
      CHECK (length(text) BETWEEN 1 AND ${MESSAGE_TEXT_MAX})
    ) STRICT;
  `
}

