function createSchema(database) {
  withImmediateTransaction(database, () => {
    // Re-read inside the write transaction: a concurrent opener may have
    // created the schema between our outer probe and this transaction. The
    // loser of that race no-ops instead of crashing on existing tables.
    const current = Number(pragmaValue(database, 'PRAGMA user_version'))
    if (current === ROOM_LOG_SCHEMA_VERSION) return
    if (current !== 0) {
      fail(
        'database_schema_unsupported',
        `database schema ${current} is not supported; expected ${ROOM_LOG_SCHEMA_VERSION} (the one-time v1→v2 migration runs at server startup, never on this raw store path)`,
      )
    }

    database.exec(`
      ${roomsTableDdl('rooms')}

      ${directMembersTableDdl()}

      ${messagesTableDdl('messages')}

      PRAGMA user_version = ${ROOM_LOG_SCHEMA_VERSION};
    `)
  })
}

// Schema probe: fresh files (user_version 0) proceed to schema creation;
// version 2 files proceed to verification; anything else — a v1 file above
// all — is refused untouched, because migration belongs to Epic 2. A version
// 0 file that already carries application tables is likewise refused rather
// than crashed into. The probe runs BEFORE any pragma or permission change so
// a refused file's bytes are never modified by this store.
function probeSchemaVersion(database) {
  // The version and table-structure reads must share one snapshot: a
  // concurrent opener commits (tables + user_version = 2) atomically, and a
  // two-read probe without a transaction could straddle that commit and
  // mistake a legitimate v2 file for a v0 file carrying foreign tables. A
  // deferred read transaction gives both reads one consistent snapshot.
  database.exec('BEGIN DEFERRED')
  try {
    let version
    try {
      version = Number(pragmaValue(database, 'PRAGMA user_version'))
    } catch (error) {
      if (error?.errcode === SQLITE_NOTADB || error?.errcode === SQLITE_CORRUPT) {
        fail('database_schema_unsupported', 'existing database file is not a usable SQLite database')
      }
      throw error
    }
    if (version === ROOM_LOG_SCHEMA_VERSION) return version
    if (version !== 0) {
      fail(
        'database_schema_unsupported',
        `database schema ${version} is not supported; expected ${ROOM_LOG_SCHEMA_VERSION} (the one-time v1→v2 migration runs at server startup, never on this raw store path)`,
      )
    }
    let applicationTables
    try {
      applicationTables = Number(database.prepare(`
        SELECT COUNT(*) AS count
        FROM sqlite_master
        WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
      `).get().count)
    } catch (error) {
      if (error?.errcode === SQLITE_BUSY) {
        fail('database_busy', 'agent-room database stayed busy while probing the schema version')
      }
      throw error
    }
    if (applicationTables > 0) {
      fail(
        'database_schema_unsupported',
        'database file already contains tables at schema version 0 and cannot be adopted',
      )
    }
    return 0
  } finally {
    try {
      database.exec('COMMIT')
    } catch {
      try {
        database.exec('ROLLBACK')
      } catch {
        // The connection is failing; the caller closes it.
      }
    }
  }
}

function isUnusableDatabaseError(error) {
  return error?.errcode === SQLITE_NOTADB || error?.errcode === SQLITE_CORRUPT
}

// Synchronous backoff for the open path: concurrent openers must not fail
// fast, and the open sequence is synchronous, so the retry sleeps via
// Atomics.wait (a short blocking wait is acceptable during startup).
function sleepSync(milliseconds) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, milliseconds)
}

function isBusyError(error) {
  return error?.errcode === SQLITE_BUSY
    || (error instanceof AgentRoomRuntimeError && error.code === 'database_busy')
}

function withBusyRetry(operation) {
  let attempt = 0
  for (;;) {
    try {
      return operation()
    } catch (error) {
      attempt += 1
      if (!isBusyError(error) || attempt > STORE_OPEN_BUSY_RETRY_LIMIT) throw error
      sleepSync(STORE_OPEN_BUSY_BACKOFF_MS * attempt)
    }
  }
}

function verifyStrictTables(database) {
  const strictTables = database.prepare(`
    SELECT name, strict
    FROM pragma_table_list
    WHERE schema = 'main'
      AND name IN ('rooms', 'direct_members', 'messages', 'realms', 'chat_id_claims', 'enrolled_actors')
  `).all()
  const strictByName = new Map(strictTables.map(row => [row.name, Number(row.strict)]))
  for (const name of ['rooms', 'direct_members', 'messages', 'realms', 'chat_id_claims', 'enrolled_actors']) {
    if (strictByName.get(name) !== 1) {
      fail('database_schema_invalid', `database table ${name} is missing or is not STRICT`)
    }
  }
}

// Story 1.3 (additive, no schema-version bump): the realms table joins the
// schema additively. CREATE TABLE IF NOT EXISTS keeps fresh v2 files and files
// created by earlier Epic-1 builds converging on the same shape on every
// open, and the singleton PRIMARY KEY enforces the at-most-one-realm
// invariant at the schema level (AD-14: one process = one realm).
function ensureRealmTable(database) {
  database.exec(realmsTableDdl({ ifNotExists: true }))
}

// Story 1.3 review fix (additive, no schema-version bump): the implicit
// Broadcast Room has no Actor creator, so rooms.created_by_fingerprint must be
// nullable. Fresh files build the nullable shape directly; v2 files created
// before this fix carry NOT NULL and converge on open via the standard SQLite
// table-rebuild recipe (foreign keys off, create-copy-drop-rename inside one
// write transaction, foreign keys restored), preserving every row.
function ensureNullableRoomCreator(database) {
  // "notnull" is quoted: bare, it parses as SQLite's postfix NOTNULL operator.
  const column = database
    .prepare(`SELECT "notnull" AS "notnull" FROM pragma_table_info('rooms') WHERE name = 'created_by_fingerprint'`)
    .get()
  if (!column || Number(column.notnull) === 0) return

  database.exec('PRAGMA foreign_keys = OFF;')
  try {
    withImmediateTransaction(database, () => {
      database.exec(roomsTableDdl('rooms_new'))
      database.exec(`
        INSERT INTO rooms_new (id, kind, title, pair_key, created_by_fingerprint, created_at)
        SELECT id, kind, title, pair_key, created_by_fingerprint, created_at
        FROM rooms;
      `)
      database.exec('DROP TABLE rooms;')
      database.exec('ALTER TABLE rooms_new RENAME TO rooms;')
    })
  } finally {
    database.exec('PRAGMA foreign_keys = ON;')
  }

  const restored = database
    .prepare(`SELECT "notnull" AS "notnull" FROM pragma_table_info('rooms') WHERE name = 'created_by_fingerprint'`)
    .get()
  if (!restored || Number(restored.notnull) !== 0) {
    fail('database_schema_invalid', 'rooms.created_by_fingerprint did not converge to nullable')
  }
}

// Story 1.5 (additive, no schema-version bump): the durable chat_id_claims
// index — one row per (normalized chat id, actor fingerprint) pair with the
// display form and last_seen_at — joins the schema via the same IF NOT EXISTS
// convergence pattern as the realms table. Multiple Actors may hold claims on
// one name (exactly the ambiguity data room_direct_open resolves), and
// historical (name, actor) pairs persist after rename or disconnect. Live
// uniqueness is deliberately NOT a property of this table: it is the
// in-memory live-session registry's rule, so no schema beyond this additive
// index is required. The CHECK pins the normalization invariant — the
// normalized form is the ASCII-lowercased display form, which the grammar's
// character class makes exact.
function ensureChatIdClaimsTable(database) {
  database.exec(chatIdClaimsTableDdl({ ifNotExists: true }))
}

// Story 1.6 (additive, no schema-version bump): the offline-recently read
// (recentClaims) window-scans this table by last_seen_at, so the query gets
// an index instead of a full scan. IF NOT EXISTS converges every open, and
// the named-index verification below refuses a foreign squatter. The index
// joins AFTER the column verification so a divergent pre-existing table
// fails coded before the index build ever touches it.
function ensureChatIdClaimsLastSeenIndex(database) {
  database.exec(`
    CREATE INDEX IF NOT EXISTS idx_chat_id_claims_last_seen_at
      ON chat_id_claims (last_seen_at);
  `)
}

// Story 1.5 review hardening: CREATE TABLE IF NOT EXISTS silently keeps a
// pre-existing table of a different shape, so the column set is verified
// right after the convergence step — a foreign or drifted chat_id_claims is a
// coded schema failure at open, never a runtime surprise mid-write.
const CHAT_ID_CLAIMS_COLUMNS = Object.freeze([
  'chat_id_normalized',
  'actor_fingerprint',
  'chat_id_display',
  'last_seen_at',
])

function verifyChatIdClaimsColumns(database) {
  const columns = database
    .prepare(`SELECT name FROM pragma_table_info('chat_id_claims') ORDER BY cid`)
    .all()
    .map(row => row.name)
  if (
    columns.length !== CHAT_ID_CLAIMS_COLUMNS.length
    || CHAT_ID_CLAIMS_COLUMNS.some((name, index) => columns[index] !== name)
  ) {
    fail('database_schema_invalid', 'database table chat_id_claims has a divergent column set')
  }
}

// Story 1.6: the last-seen index joins the convergence discipline — the
// named index must exist after the open (IF NOT EXISTS recreates a dropped
