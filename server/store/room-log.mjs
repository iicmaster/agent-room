function requireClientMessageId(value) {
  if (typeof value !== 'string' || !CLIENT_MESSAGE_ID_PATTERN.test(value)) {
    fail(
      'invalid_client_message_id',
      `clientMessageId must be 1-${CLIENT_MESSAGE_ID_MAX} characters using letters, numbers, dot, underscore, colon, or hyphen`,
    )
  }
  return value
}

// A lone surrogate code point cannot be encoded to UTF-8: SQLite would store
// U+FFFD in its place, so the stored bytes would differ from the input and an
// exact idempotent resend would report a payload conflict. Such text is
// rejected outright; paired surrogates (astral code points) are fine.
function containsUnpairedSurrogate(value) {
  for (const char of value) {
    const code = char.codePointAt(0)
    if (code >= 0xd800 && code <= 0xdfff) return true
  }
  return false
}

function requireMessageText(value) {
  if (
    typeof value !== 'string'
    || value.trim().length === 0
    || value.length > MESSAGE_TEXT_MAX
    || /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/u.test(value)
    || containsUnpairedSurrogate(value)
  ) {
    fail(
      'invalid_text',
      `text must contain 1-${MESSAGE_TEXT_MAX} characters with no unsupported control bytes or lone surrogates`,
    )
  }
  return value
}

function requireTitle(value, fallback) {
  if (value === undefined || value === null) return fallback
  if (typeof value !== 'string') {
    fail('invalid_title', 'title must be a string')
  }
  const normalized = value.trim()
  if (
    normalized.length === 0
    || normalized.length > TITLE_MAX
    || /[\u0000-\u001f\u007f]/u.test(normalized)
    || containsUnpairedSurrogate(normalized)
  ) {
    fail('invalid_title', `title must be 1-${TITLE_MAX} printable characters with no lone surrogates`)
  }
  return normalized
}

function requireAfterSeq(value) {
  if (!Number.isSafeInteger(value) || value < 0) {
    fail('invalid_cursor', 'afterSeq must be a non-negative safe integer')
  }
  return value
}

function requireReadLimit(value) {
  if (!Number.isSafeInteger(value) || value < 1 || value > READ_PAGE_MAX) {
    fail('invalid_limit', `limit must be an integer from 1-${READ_PAGE_MAX}`)
  }
  return value
}

function requireReplyToSeq(value) {
  if (value === null || value === undefined) return null
  if (!Number.isSafeInteger(value) || value < 1) {
    fail('invalid_reply_to_seq', 'replyToSeq must be null or a positive safe integer')
  }
  return value
}

// Canonical DM pair identity: the two fingerprints sorted lexicographically,
// so (a, b) and (b, a) derive the same key and openDirectRoom is idempotent
// in either argument order. Fingerprints are fixed length, so the sort is
// stable. The lexicographic minimum doubles as the deterministic
// created_by_fingerprint for a direct room.
function canonicalDirectPair(firstFingerprint, secondFingerprint) {
  const [min, max] = [firstFingerprint, secondFingerprint].sort()
  return Object.freeze({ min, max, pairKey: `${DIRECT_PAIR_KEY_PREFIX}${min}:${max}` })
}

function pragmaValue(database, sql) {
  const row = database.prepare(sql).get()
  return row ? Object.values(row)[0] : undefined
}

// Pragma discipline mirrors the v0.1 store's configureConnection exactly:
// WAL, synchronous=FULL, foreign keys ON, busy_timeout 5000,
// wal_autocheckpoint 1000 — asserted after applying, never assumed. The busy
// timeout is applied FIRST: it is the only guard for the journal-mode switch,
// which is the open path's first contended write under concurrent openers.
function configureConnection(database) {
  const sqliteVersion = String(
    database.prepare('SELECT sqlite_version() AS version').get().version,
  )
  assertSupportedRuntime({ sqliteVersion })

  database.exec('PRAGMA busy_timeout = 5000;')

  let journalMode
  try {
    journalMode = String(pragmaValue(database, 'PRAGMA journal_mode = WAL')).toLowerCase()
  } catch (error) {
    if (error?.errcode === SQLITE_BUSY) {
      fail('database_busy', 'agent-room database stayed busy while enabling WAL journal mode')
    }
    throw error
  }
  if (journalMode !== 'wal') {
    fail('wal_unavailable', 'agent-room requires SQLite WAL journal mode')
  }

  database.exec(`
    PRAGMA synchronous = FULL;
    PRAGMA foreign_keys = ON;
    PRAGMA busy_timeout = 5000;
    PRAGMA wal_autocheckpoint = 1000;
  `)

  const pragmas = Object.freeze({
    synchronous: Number(pragmaValue(database, 'PRAGMA synchronous')),
    foreignKeys: Number(pragmaValue(database, 'PRAGMA foreign_keys')) === 1,
    busyTimeout: Number(pragmaValue(database, 'PRAGMA busy_timeout')),
    walAutoCheckpoint: Number(pragmaValue(database, 'PRAGMA wal_autocheckpoint')),
  })
  if (
    pragmas.synchronous !== 2
    || pragmas.foreignKeys !== true
    || pragmas.busyTimeout !== 5000
    || pragmas.walAutoCheckpoint !== 1000
  ) {
    fail('database_configuration_failed', 'SQLite connection pragmas were not applied')
  }
  return { sqliteVersion, journalMode, pragmas }
}

function withImmediateTransaction(database, operation) {
  try {
    database.exec('BEGIN IMMEDIATE')
  } catch (error) {
    // Under contention the connection waits busy_timeout, then surfaces
    // SQLITE_BUSY: the write never started, so it maps to a coded internal
    // error instead of a raw SqliteError.
    if (error?.errcode === SQLITE_BUSY) {
      fail('database_busy', 'agent-room database write lock stayed busy; the operation never started')
    }
    throw error
  }
  try {
    const result = operation()
    database.exec('COMMIT')
    return result
  } catch (error) {
    try {
      database.exec('ROLLBACK')
    } catch {
      // Preserve the operation error; the connection will surface later failures.
    }
    throw error
  }
}

// A CHECK clause enforcing the exact fingerprint shape at the schema level:
// fixed total length, the sha256: prefix, and a 64-character tail drawn only
// from [0-9a-f] (the NOT GLOB guarantees no character outside the class).
// SQLite CHECKs pass on NULL results, so this also admits the NULL creator of
// the implicit Broadcast Room.
function fingerprintCheck(column) {
  const tailStart = FINGERPRINT_PREFIX.length + 1
  return `CHECK (length(${column}) = ${FINGERPRINT_PREFIX.length + FINGERPRINT_HEX_LENGTH}
          AND substr(${column}, 1, ${FINGERPRINT_PREFIX.length}) = '${FINGERPRINT_PREFIX}'
          AND substr(${column}, ${tailStart}) NOT GLOB '*[^0-9a-f]*')`
}

// The rooms table DDL, parameterized by table name so the nullable-creator
// convergence rebuild (ensureNullableRoomCreator) shares one definition with
// createSchema. created_by_fingerprint is NULLABLE: the implicit Broadcast
// Room exists before any Actor enrolls and must never carry a fabricated
// creator identity.
function roomsTableDdl(tableName) {
  return `
    CREATE TABLE ${tableName} (
      id TEXT PRIMARY KEY,
      kind TEXT NOT NULL,
      title TEXT,
      pair_key TEXT UNIQUE,
      created_by_fingerprint TEXT,
      created_at TEXT NOT NULL,
      CHECK (kind IN ('broadcast', 'direct')),
      CHECK ((kind = 'direct') = (pair_key IS NOT NULL)),
      CHECK (kind = 'direct' OR title IS NOT NULL),
      CHECK (kind = 'direct' OR length(title) BETWEEN 1 AND ${TITLE_MAX}),
      CHECK (length(id) BETWEEN 1 AND ${IDENTIFIER_MAX}),
      ${fingerprintCheck('created_by_fingerprint')}
    ) STRICT;
  `
}

function createSchema(database) {
  withImmediateTransaction(database, () => {
    // Re-read inside the write transaction: a concurrent opener may have
    // created the schema between our outer probe and this transaction. The
    // loser of that race no-ops instead of crashing on existing tables.
    const current = Number(pragmaValue(database, 'PRAGMA user_version'))
    if (current === ROOM_LOG_SCHEMA_VERSION) return
    if (current !== 0) {
      fail(
        'database_schema_unsupported',
        `database schema ${current} is not supported; expected ${ROOM_LOG_SCHEMA_VERSION} (migration is not supported by this store)`,
      )
    }

    database.exec(`
      ${roomsTableDdl('rooms')}

      -- Membership rows exist ONLY for direct rooms; broadcast membership is
      -- implicit (AD-14), so broadcast append/read needs no membership row.
      CREATE TABLE direct_members (
        room_id TEXT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
        actor_fingerprint TEXT NOT NULL,
        joined_at TEXT NOT NULL,
        PRIMARY KEY (room_id, actor_fingerprint),
        ${fingerprintCheck('actor_fingerprint')}
      ) STRICT;

      -- The durable log: keyed (room_id, seq), room-local contiguous
      -- sequences from 1, and no mutation path of any kind. The composite
      -- primary key is what makes reply targets room-local.
      CREATE TABLE messages (
        room_id TEXT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
        seq INTEGER NOT NULL,
        actor_fingerprint TEXT NOT NULL,
        chat_id TEXT NOT NULL,
        client_message_id TEXT NOT NULL,
        text TEXT NOT NULL,
        reply_to_seq INTEGER,
        created_at TEXT NOT NULL,
        PRIMARY KEY (room_id, seq),
        UNIQUE (room_id, actor_fingerprint, client_message_id),
        FOREIGN KEY (room_id, reply_to_seq)
          REFERENCES messages(room_id, seq) ON DELETE RESTRICT,
        CHECK (seq >= 1),
        CHECK (reply_to_seq IS NULL OR reply_to_seq >= 1),
        ${fingerprintCheck('actor_fingerprint')},
        CHECK (length(chat_id) BETWEEN 1 AND ${CHAT_ID_MAX}),
        CHECK (length(client_message_id) BETWEEN 1 AND ${CLIENT_MESSAGE_ID_MAX}),
        CHECK (length(text) BETWEEN 1 AND ${MESSAGE_TEXT_MAX})
      ) STRICT;

      PRAGMA user_version = ${ROOM_LOG_SCHEMA_VERSION};
    `)
  })
}

// Schema probe: fresh files (user_version 0) proceed to schema creation;
// version 2 files proceed to verification; anything else — a v1 file above
// all — is refused untouched, because migration belongs to Epic 2. A version
// 0 file that already carries application tables is likewise refused rather
// than crashed into. The probe runs BEFORE any pragma or permission change so
// a refused file's bytes are never modified by this store.
function probeSchemaVersion(database) {
  // The version and table-structure reads must share one snapshot: a
  // concurrent opener commits (tables + user_version = 2) atomically, and a
  // two-read probe without a transaction could straddle that commit and
  // mistake a legitimate v2 file for a v0 file carrying foreign tables. A
  // deferred read transaction gives both reads one consistent snapshot.
  database.exec('BEGIN DEFERRED')
  try {
    let version
    try {
      version = Number(pragmaValue(database, 'PRAGMA user_version'))
    } catch (error) {
      if (error?.errcode === SQLITE_NOTADB || error?.errcode === SQLITE_CORRUPT) {
        fail('database_schema_unsupported', 'existing database file is not a usable SQLite database')
      }
      throw error
    }
    if (version === ROOM_LOG_SCHEMA_VERSION) return version
    if (version !== 0) {
      fail(
        'database_schema_unsupported',
        `database schema ${version} is not supported; expected ${ROOM_LOG_SCHEMA_VERSION} (migration is not supported by this store)`,
      )
    }
    let applicationTables
    try {
      applicationTables = Number(database.prepare(`
        SELECT COUNT(*) AS count
        FROM sqlite_master
        WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
      `).get().count)
    } catch (error) {
      if (error?.errcode === SQLITE_BUSY) {
        fail('database_busy', 'agent-room database stayed busy while probing the schema version')
      }
      throw error
    }
    if (applicationTables > 0) {
      fail(
        'database_schema_unsupported',
        'database file already contains tables at schema version 0 and cannot be adopted',
      )
    }
    return 0
  } finally {
    try {
      database.exec('COMMIT')
    } catch {
      try {
        database.exec('ROLLBACK')
      } catch {
        // The connection is failing; the caller closes it.
      }
    }
  }
}

function isUnusableDatabaseError(error) {
  return error?.errcode === SQLITE_NOTADB || error?.errcode === SQLITE_CORRUPT
}

// Synchronous backoff for the open path: concurrent openers must not fail
// fast, and the open sequence is synchronous, so the retry sleeps via
// Atomics.wait (a short blocking wait is acceptable during startup).
function sleepSync(milliseconds) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, milliseconds)
}

function isBusyError(error) {
  return error?.errcode === SQLITE_BUSY
    || (error instanceof AgentRoomRuntimeError && error.code === 'database_busy')
}

function withBusyRetry(operation) {
  let attempt = 0
  for (;;) {
    try {
      return operation()
    } catch (error) {
      attempt += 1
      if (!isBusyError(error) || attempt > STORE_OPEN_BUSY_RETRY_LIMIT) throw error
      sleepSync(STORE_OPEN_BUSY_BACKOFF_MS * attempt)
    }
  }
}

function verifyStrictTables(database) {
  const strictTables = database.prepare(`
    SELECT name, strict
    FROM pragma_table_list
    WHERE schema = 'main'
      AND name IN ('rooms', 'direct_members', 'messages', 'realms')
  `).all()
  const strictByName = new Map(strictTables.map(row => [row.name, Number(row.strict)]))
  for (const name of ['rooms', 'direct_members', 'messages', 'realms']) {
    if (strictByName.get(name) !== 1) {
      fail('database_schema_invalid', `database table ${name} is missing or is not STRICT`)
    }
  }
}

// Story 1.3 (additive, no schema-version bump): the realms table joins the
// schema additively. CREATE TABLE IF NOT EXISTS keeps fresh v2 files and files
// created by earlier Epic-1 builds converging on the same shape on every
// open, and the singleton PRIMARY KEY enforces the at-most-one-realm
// invariant at the schema level (AD-14: one process = one realm).
function ensureRealmTable(database) {
  database.exec(`
    CREATE TABLE IF NOT EXISTS realms (
      singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
      realm_id TEXT NOT NULL UNIQUE,
      created_at TEXT NOT NULL
    ) STRICT;
  `)
}

// Story 1.3 review fix (additive, no schema-version bump): the implicit
// Broadcast Room has no Actor creator, so rooms.created_by_fingerprint must be
// nullable. Fresh files build the nullable shape directly; v2 files created
// before this fix carry NOT NULL and converge on open via the standard SQLite
// table-rebuild recipe (foreign keys off, create-copy-drop-rename inside one
// write transaction, foreign keys restored), preserving every row.
function ensureNullableRoomCreator(database) {
  // "notnull" is quoted: bare, it parses as SQLite's postfix NOTNULL operator.
  const column = database
    .prepare(`SELECT "notnull" AS "notnull" FROM pragma_table_info('rooms') WHERE name = 'created_by_fingerprint'`)
    .get()
  if (!column || Number(column.notnull) === 0) return

  database.exec('PRAGMA foreign_keys = OFF;')
  try {
    withImmediateTransaction(database, () => {
      database.exec(roomsTableDdl('rooms_new'))
      database.exec(`
        INSERT INTO rooms_new (id, kind, title, pair_key, created_by_fingerprint, created_at)
        SELECT id, kind, title, pair_key, created_by_fingerprint, created_at
        FROM rooms;
      `)
      database.exec('DROP TABLE rooms;')
      database.exec('ALTER TABLE rooms_new RENAME TO rooms;')
    })
  } finally {
    database.exec('PRAGMA foreign_keys = ON;')
  }

  const restored = database
    .prepare(`SELECT "notnull" AS "notnull" FROM pragma_table_info('rooms') WHERE name = 'created_by_fingerprint'`)
    .get()
  if (!restored || Number(restored.notnull) !== 0) {
    fail('database_schema_invalid', 'rooms.created_by_fingerprint did not converge to nullable')
  }
}

function plainMessage(row) {
  return {
    seq: Number(row.seq),
    room_id: row.room_id,
    actor_fingerprint: row.actor_fingerprint,
    chat_id: row.chat_id,
    client_message_id: row.client_message_id,
    text: row.text,
    reply_to_seq: row.reply_to_seq === null ? null : Number(row.reply_to_seq),
    created_at: row.created_at,
  }
}

function plainRoom(row) {
  return {
    id: row.id,
    kind: row.kind,
    title: row.title === null ? null : String(row.title),
    pair_key: row.pair_key === null ? null : String(row.pair_key),
    created_by_fingerprint: row.created_by_fingerprint,
    created_at: row.created_at,
  }
}

export function openRoomLog({ dataDir } = {}) {
  if (typeof dataDir !== 'string' || dataDir.trim().length === 0) {
    fail('data_directory_invalid', 'dataDir must be a non-empty path')
  }

  const directory = ensurePrivateDirectory(dataDir)
  const databasePath = join(directory, ROOM_LOG_DATABASE_FILENAME)

  // lstat (not existsSync) so a dangling symlink is refused too.
  let preexisting = false
  try {
    const info = lstatSync(databasePath)
    if (info.isSymbolicLink() || !info.isFile()) {
      fail('data_directory_invalid', 'agent-room database must be a regular non-symlink file')
    }
    preexisting = true
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      fail('data_directory_invalid', `agent-room database path is unusable: ${error.message}`)
    }
  }

  if (!preexisting) {
    // Pre-create at 0600 so the file never exists under a looser umask.
    let descriptor
    try {
      descriptor = openSync(databasePath, 'wx', 0o600)
    } catch (error) {
      if (error?.code !== 'EEXIST') {
        fail('data_directory_invalid', `agent-room database file could not be created: ${error.message}`)
      }
      // Lost a creation race: whoever created the file owns the schema probe.
      preexisting = true
    } finally {
      if (descriptor !== undefined) closeSync(descriptor)
    }
  }

  let database
  try {
    try {
      database = new DatabaseSync(databasePath)
    } catch (error) {
      if (isUnusableDatabaseError(error)) {
        fail('database_schema_unsupported', 'existing database file is not a usable SQLite database')
      }
      throw error
    }

    // Contention guard before the retried sequence: the schema probe below
    // reads the file while concurrent openers may hold an exclusive commit
    // phase. busy_timeout is a connection-local setting and writes nothing,
    // so refused files stay byte-for-byte untouched.
    database.exec('PRAGMA busy_timeout = 5000;')

    // The contended open sequence — probe, journal-mode switch, schema
    // creation, verification — serializes against concurrent openers. The
    // journal-mode switch in particular can return SQLITE_BUSY immediately
    // without invoking the busy handler, so the whole idempotent sequence
    // retries with a small backoff; the first opener to commit the schema
    // makes every loser a no-op via the in-transaction re-read.
    const opened = withBusyRetry(() => {
      // Probe BEFORE any pragma or permission change so a refused database
      // file is left byte-for-byte untouched.
      const probedVersion = probeSchemaVersion(database)

      chmodSync(databasePath, 0o600)
      const connection = configureConnection(database)

      if (probedVersion === 0) createSchema(database)
      ensureRealmTable(database)
      ensureNullableRoomCreator(database)
      verifyStrictTables(database)

      // Report the file's actual version, never the compiled constant.
      const reportedVersion = Number(pragmaValue(database, 'PRAGMA user_version'))
      if (reportedVersion !== ROOM_LOG_SCHEMA_VERSION) {
        fail('database_schema_invalid', `database user_version ${reportedVersion} did not become ${ROOM_LOG_SCHEMA_VERSION}`)
      }
      return { ...connection, reportedVersion }
    })
    const { sqliteVersion, journalMode, pragmas, reportedVersion } = opened

    // WAL sidecars are recreated on every open; keep them owner-only too.
    for (const sidecar of [`${databasePath}-wal`, `${databasePath}-shm`]) {
      if (existsSync(sidecar)) chmodSync(sidecar, 0o600)
    }

    const selectRoom = roomId => database
      .prepare('SELECT id, kind, title, pair_key, created_by_fingerprint, created_at FROM rooms WHERE id = ?')
      .get(roomId)

    const requireRoom = roomId => {
      const room = selectRoom(roomId)
      if (!room) fail('room_not_found', `room ${roomId} does not exist`)
      return room
    }

    // Protocol-level DM privacy at the store boundary: only direct rooms
    // consult membership; broadcast rooms are open to every Actor (AD-14).
    const requireDirectMembership = (room, actorFingerprint) => {
      if (room.kind !== DIRECT_KIND) return
      const member = database.prepare(`
        SELECT 1 AS found
        FROM direct_members
        WHERE room_id = ? AND actor_fingerprint = ?
      `).get(room.id, actorFingerprint)
      if (!member) {
        fail('actor_not_member', `actor is not a member of room ${room.id}`)
      }
    }

    const selectMessage = (roomId, seq) => {
      const row = database.prepare(`${MESSAGE_PROJECTION} WHERE room_id = ? AND seq = ?`)
        .get(roomId, seq)
      return row ? plainMessage(row) : null
    }

    let closed = false
    const assertOpen = () => {
      if (closed) fail('store_connection_closed', 'agent-room store connection is closed')
    }

    const api = {
      databasePath,
      schemaVersion: reportedVersion,
      sqliteVersion,
      journalMode,
      pragmas,

      close() {
        if (closed) return
        database.close()
        closed = true
      },

      // Broadcast rooms are open by design: created with an optional title
      // (defaults when omitted) and no membership rows. The creator is
      // optional too: the implicit Broadcast Room is bootstrapped before any
      // Actor exists and carries a NULL created_by_fingerprint — the store
      // never fabricates an identity for it.
      createBroadcastRoom(options) {
        assertOpen()
        const { actorFingerprint = null, title } = requireObject(options)
        const validFingerprint = actorFingerprint === null ? null : requireFingerprint(actorFingerprint)
        const validTitle = requireTitle(title, DEFAULT_BROADCAST_TITLE)
        const id = randomBytes(ROOM_ID_ENTROPY_BYTES).toString('base64url')
        const createdAt = new Date().toISOString()

        return withImmediateTransaction(database, () => {
          database.prepare(`
            INSERT INTO rooms (id, kind, title, pair_key, created_by_fingerprint, created_at)
            VALUES (?, ?, ?, NULL, ?, ?)
          `).run(id, BROADCAST_KIND, validTitle, validFingerprint, createdAt)
          return {
            id,
            kind: BROADCAST_KIND,
            title: validTitle,
            pair_key: null,
            created_by_fingerprint: validFingerprint,
            created_at: createdAt,
          }
        })
      },

      // Atomic bootstrap ensure: re-checks for an existing Broadcast Room
      // INSIDE the write transaction, so concurrent or retried bootstraps
      // converge on exactly one commons room instead of racing two inserts.
      // Creates the room with a NULL creator (never a fabricated identity).
      ensureBroadcastRoom(options = {}) {
        assertOpen()
        const { title } = requireObject(options)
        const validTitle = requireTitle(title, DEFAULT_BROADCAST_TITLE)

        return withImmediateTransaction(database, () => {
          const existingRow = database.prepare(`
            SELECT id, kind, title, pair_key, created_by_fingerprint, created_at
            FROM rooms
            WHERE kind = 'broadcast'
            ORDER BY created_at ASC, id ASC
            LIMIT 1
          `).get()
          if (existingRow) return plainRoom(existingRow)

          const id = randomBytes(ROOM_ID_ENTROPY_BYTES).toString('base64url')
          const createdAt = new Date().toISOString()
          database.prepare(`
            INSERT INTO rooms (id, kind, title, pair_key, created_by_fingerprint, created_at)
            VALUES (?, ?, ?, NULL, NULL, ?)
          `).run(id, BROADCAST_KIND, validTitle, createdAt)
          return {
            id,
            kind: BROADCAST_KIND,
            title: validTitle,
            pair_key: null,
            created_by_fingerprint: null,
            created_at: createdAt,
          }
        })
      },

      // Direct rooms: canonical pair key, idempotent by UNIQUE(pair_key) in
      // either argument order. Same fingerprint twice opens a same-Actor
      // room. Direct rooms carry no stored title — DM labeling belongs to
      // the chat ids on the messages, which are never rewritten.
      openDirectRoom(options) {
        assertOpen()
        const { actorFingerprints } = requireObject(options)
        if (!Array.isArray(actorFingerprints) || actorFingerprints.length !== 2) {
          fail('invalid_actor_id', 'actorFingerprints must contain exactly two fingerprints')
        }
        const [firstFingerprint, secondFingerprint] = actorFingerprints.map(requireFingerprint)
        const { min, max, pairKey } = canonicalDirectPair(firstFingerprint, secondFingerprint)
        const createdAt = new Date().toISOString()

        return withImmediateTransaction(database, () => {
          const existingRow = database
            .prepare('SELECT id, kind, title, pair_key, created_by_fingerprint, created_at FROM rooms WHERE pair_key = ?')
            .get(pairKey)
          let room
          if (existingRow) {
            room = plainRoom(existingRow)
          } else {
            const id = randomBytes(ROOM_ID_ENTROPY_BYTES).toString('base64url')
            database.prepare(`
              INSERT INTO rooms (id, kind, title, pair_key, created_by_fingerprint, created_at)
              VALUES (?, ?, NULL, ?, ?, ?)
            `).run(id, DIRECT_KIND, pairKey, min, createdAt)
            room = {
              id,
              kind: DIRECT_KIND,
              title: null,
              pair_key: pairKey,
              created_by_fingerprint: min,
              created_at: createdAt,
            }
          }

          for (const fingerprint of new Set([firstFingerprint, secondFingerprint])) {
            database.prepare(`
              INSERT INTO direct_members (room_id, actor_fingerprint, joined_at)
              VALUES (?, ?, ?)
              ON CONFLICT (room_id, actor_fingerprint) DO NOTHING
            `).run(room.id, fingerprint, createdAt)
          }
          return room
        })
      },

      // Append to the durable log. Sequences are room-local, contiguous from
      // 1, and assigned inside this BEGIN IMMEDIATE transaction via
      // MAX(seq)+1 — gap-free because the single writer serializes appends
      // (AD-2). Idempotency tuple (actor fingerprint, room,
      // client_message_id) is checked before the insert: a matching payload
      // returns the original message, a differing payload is a conflict.
      // The chat id is stored at send time as attribution and never
      // rewritten; it is therefore not part of the payload comparison.
      appendMessage(options) {
        assertOpen()
        const {
          roomId,
          actorFingerprint,
          chatId,
          clientMessageId,
          text,
          replyToSeq = null,
        } = requireObject(options)
        const validRoomId = requireRoomId(roomId)
        const validFingerprint = requireFingerprint(actorFingerprint)
        const validChatId = requireChatId(chatId)
        const validClientMessageId = requireClientMessageId(clientMessageId)
        const validText = requireMessageText(text)
        const validReplyToSeq = requireReplyToSeq(replyToSeq)

        return withImmediateTransaction(database, () => {
          const room = requireRoom(validRoomId)
          requireDirectMembership(room, validFingerprint)

          const existingRow = database.prepare(`
            ${MESSAGE_PROJECTION}
            WHERE room_id = ? AND actor_fingerprint = ? AND client_message_id = ?
          `).get(validRoomId, validFingerprint, validClientMessageId)
          if (existingRow) {
            const existing = plainMessage(existingRow)
            if (existing.text !== validText || existing.reply_to_seq !== validReplyToSeq) {
              fail(
                'client_message_id_conflict',
                'clientMessageId was already used with a different message payload',
              )
            }
            return { message: existing, duplicate: true }
          }

          // Reply targets resolve room-locally against (room_id, seq). Only
          // when the seq is absent from this room does a global lookup
          // distinguish a cross-room target from a nonexistent one.
          if (validReplyToSeq !== null) {
            const localTarget = database
              .prepare('SELECT 1 AS found FROM messages WHERE room_id = ? AND seq = ?')
              .get(validRoomId, validReplyToSeq)
            if (!localTarget) {
              const foreignTarget = database
                .prepare('SELECT 1 AS found FROM messages WHERE seq = ? AND room_id <> ?')
                .get(validReplyToSeq, validRoomId)
              if (foreignTarget) {
                fail('reply_room_mismatch', 'replyToSeq identifies a message in another room')
              }
              fail('message_not_found', 'replyToSeq does not identify an existing message')
            }
          }

          const nextSeq = Number(database
            .prepare('SELECT COALESCE(MAX(seq), 0) + 1 AS next_seq FROM messages WHERE room_id = ?')
            .get(validRoomId).next_seq)
          const createdAt = new Date().toISOString()
          database.prepare(`
            INSERT INTO messages (
              room_id,
              seq,
              actor_fingerprint,
              chat_id,
              client_message_id,
              text,
              reply_to_seq,
              created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
          `).run(
            validRoomId,
            nextSeq,
            validFingerprint,
            validChatId,
            validClientMessageId,
            validText,
            validReplyToSeq,
            createdAt,
          )
          return { message: selectMessage(validRoomId, nextSeq), duplicate: false }
        })
      },

      // Cursor page over the room-local log: strictly-greater afterSeq, seq
      // ASC, bounded limit. Direct rooms deny non-members both here and on
      // append.
      readPage(options) {
        assertOpen()
        const {
          roomId,
          actorFingerprint,
          afterSeq = 0,
          limit = READ_PAGE_MAX,
        } = requireObject(options)
        const validRoomId = requireRoomId(roomId)
        const validFingerprint = requireFingerprint(actorFingerprint)
        const validAfterSeq = requireAfterSeq(afterSeq)
        const validLimit = requireReadLimit(limit)

        const room = requireRoom(validRoomId)
        requireDirectMembership(room, validFingerprint)

        const rows = database.prepare(`
          ${MESSAGE_PROJECTION}
          WHERE room_id = ? AND seq > ?
          ORDER BY seq ASC
          LIMIT ?
        `).all(validRoomId, validAfterSeq, validLimit)
        return rows.map(plainMessage)
      },

      // Room metadata. Direct rooms are private: the caller must present a
      // member fingerprint (the pair key embeds both fingerprints, so an
      // unguarded row would leak identities to any id-holder). Broadcast
      // rooms stay open; a provided fingerprint is still validated.
      getRoom(roomId, options = {}) {
        assertOpen()
        const validRoomId = requireRoomId(roomId)
        const { actorFingerprint = null } = requireObject(options)

        const row = selectRoom(validRoomId)
        if (!row) fail('room_not_found', `room ${validRoomId} does not exist`)

        if (row.kind === DIRECT_KIND) {
          if (actorFingerprint === null) {
            fail('invalid_actor_id', 'actorFingerprint is required to inspect a direct room')
          }
          requireDirectMembership(row, requireFingerprint(actorFingerprint))
        } else if (actorFingerprint !== null) {
          requireFingerprint(actorFingerprint)
        }
        return plainRoom(row)
      },

      // Realm bootstrap primitives (Story 1.3, AD-14): getRealmId returns the
      // minted realm id or null before first boot; insertRealm mints exactly
      // one realm row (the singleton PRIMARY KEY plus an in-transaction
      // re-read make double-minting a coded internal failure, never a silent
      // second row); findBroadcastRoom returns the implicit Broadcast Room or
      // null. Pure store operations — orchestration lives in core/realm.mjs.
      getRealmId() {
        assertOpen()
        const row = database
          .prepare('SELECT realm_id FROM realms WHERE singleton = 1')
          .get()
        return row ? String(row.realm_id) : null
      },

      insertRealm(realmId) {
        assertOpen()
        if (typeof realmId !== 'string' || !REALM_ID_PATTERN.test(realmId)) {
          fail('invalid_argument', 'realmId must be a UUID string')
        }
        const createdAt = new Date().toISOString()
        try {
          return withImmediateTransaction(database, () => {
            const existing = database
              .prepare('SELECT realm_id FROM realms WHERE singleton = 1')
              .get()
            if (existing) {
              fail('realm_already_minted', 'a realm is already minted for this data directory')
            }
            database
              .prepare('INSERT INTO realms (singleton, realm_id, created_at) VALUES (1, ?, ?)')
              .run(realmId, createdAt)
            return realmId
          })
        } catch (error) {
          // Concurrent-bootstrap convergence: a racing minter wins the
          // singleton row; the loser re-reads the minted id and returns it
          // instead of failing, so every bootstrapper agrees on one realm.
          const raced = error instanceof AgentRoomRuntimeError && error.code === 'realm_already_minted'
          if (raced || error?.errcode === SQLITE_CONSTRAINT) {
            const existing = database
              .prepare('SELECT realm_id FROM realms WHERE singleton = 1')
              .get()
            if (existing) return String(existing.realm_id)
          }
          throw error
        }
      },

      findBroadcastRoom() {
        assertOpen()
        const row = database.prepare(`
          SELECT id, kind, title, pair_key, created_by_fingerprint, created_at
          FROM rooms
          WHERE kind = 'broadcast'
          ORDER BY created_at ASC, id ASC
          LIMIT 1
        `).get()
        return row ? plainRoom(row) : null
      },
    }
    return Object.freeze(api)
  } catch (error) {
    try {
      database?.close()
    } catch {
      // Preserve the opening/configuration error.
    }
    throw error
  }
}
