// A lone surrogate code point cannot be encoded to UTF-8: SQLite would store
// U+FFFD in its place, so the stored bytes would differ from the input and an
// exact idempotent resend would report a payload conflict. Such text is
// rejected outright; paired surrogates (astral code points) are fine.
function containsUnpairedSurrogate(value) {
  for (const char of value) {
    const code = char.codePointAt(0)
    if (code >= 0xd800 && code <= 0xdfff) return true
  }
  return false
}

function requireMessageText(value) {
  if (
    typeof value !== 'string'
    || value.trim().length === 0
    || value.length > MESSAGE_TEXT_MAX
    || /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/u.test(value)
    || containsUnpairedSurrogate(value)
  ) {
    fail(
      'invalid_text',
      `text must contain 1-${MESSAGE_TEXT_MAX} characters with no unsupported control bytes or lone surrogates`,
    )
  }
  return value
}

function requireTitle(value, fallback) {
  if (value === undefined || value === null) return fallback
  if (typeof value !== 'string') {
    fail('invalid_title', 'title must be a string')
  }
  const normalized = value.trim()
  if (
    normalized.length === 0
    || normalized.length > TITLE_MAX
    || /[\u0000-\u001f\u007f]/u.test(normalized)
    || containsUnpairedSurrogate(normalized)
  ) {
    fail('invalid_title', `title must be 1-${TITLE_MAX} printable characters with no lone surrogates`)
  }
  return normalized
}

