// Room ids are opaque base64url tokens generated by this store; the bound is
// the generic identifier bound from constants.mjs.
const ROOM_ID_PATTERN = new RegExp(`^[A-Za-z0-9_-]{1,${IDENTIFIER_MAX}}$`)
// Canonical Actor fingerprint format (see ../keys.mjs): `sha256:` plus 64
// lowercase hex characters over the raw 32-byte public key.
const FINGERPRINT_PREFIX = 'sha256:'
const FINGERPRINT_HEX_LENGTH = 64
const FINGERPRINT_PATTERN = new RegExp(
  `^${FINGERPRINT_PREFIX}[0-9a-f]{${FINGERPRINT_HEX_LENGTH}}$`,
)
// Chat id grammar: 1-CHAT_ID_MAX characters of [A-Za-z0-9_.-].
const CHAT_ID_PATTERN = new RegExp(`^[A-Za-z0-9_.-]{1,${CHAT_ID_MAX}}$`)
// Realm ids are UUIDs minted at first boot (AD-14); the store validates the
// shape so the minted key is always a well-formed UUID string.
const REALM_ID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
// client_message_id grammar mirrors the v0.1 identifier grammar, bounded by
// the constants module.
const CLIENT_MESSAGE_ID_PATTERN = new RegExp(
  `^[A-Za-z0-9][A-Za-z0-9_.:-]{0,${CLIENT_MESSAGE_ID_MAX - 1}}$`,
)

const BROADCAST_KIND = 'broadcast'
const DIRECT_KIND = 'direct'
const DIRECT_PAIR_KEY_PREFIX = 'direct:'

const DEFAULT_BROADCAST_TITLE = 'Broadcast Room'

// SQLite primary result codes as reported by node:sqlite's SqliteError
// (.errcode is the numeric code; .code is Node's generic ERR_SQLITE_ERROR).
const SQLITE_BUSY = 5
const SQLITE_CORRUPT = 11
const SQLITE_NOTADB = 26
const SQLITE_CONSTRAINT = 19

